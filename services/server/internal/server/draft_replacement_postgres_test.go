//go:build integration

package server

import (
	"errors"
	"testing"
)

func TestReplaceDraftWithNewTest(t *testing.T) {
	t.Run("published", func(t *testing.T) { checkDraftReplacement(t, true) })
	t.Run("unpublished", func(t *testing.T) { checkDraftReplacement(t, false) })
}

func checkDraftReplacement(t *testing.T, published bool) {
	t.Helper()
	p, ctx := workspaceTestDB(t)
	if err := p.Migrate(ctx); err != nil {
		t.Fatal(err)
	}
	manualSeedVersions(t, p, ctx)
	files, err := NewLocalArtifacts(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	p.Artifacts = files
	h := m7DBHarness{t, p, ctx, files}
	if err := p.RegisterManager(ctx, "m7-test", 1); err != nil {
		t.Fatal(err)
	}
	testID := "10000000-0000-4000-8000-000000000001"
	if !published {
		item, err := p.CreateTest(ctx, "00000000-0000-4000-8000-000000000001", "Unpublished source", "")
		if err != nil {
			t.Fatal(err)
		}
		testID = item.ID
	}
	source, _, err := p.StartEditingSession(ctx, testID)
	if err != nil {
		t.Fatal(err)
	}
	const prompt = "改為驗證忘記密碼。\n送出後確認顯示已寄出重設信。"
	revision := source.Draft.Revision
	submission, err := p.CreateAuthor(ctx, testID, source.ID, prompt, revision)
	if err != nil {
		t.Fatal(err)
	}
	a := h.claim(submission.Run.ID)
	// The fixed sentence was generated by Workers that predate the structured flag.
	h.upload(a, "author.json", `{"message":"兩者驗證的功能不同。\n\n請使用「新增測試」，把這個流程建立成獨立的測試案例。","requestValidation":false}`)
	h.complete(a, "succeeded")
	conversation, err := p.Conversation(ctx, testID, source.ID)
	if err != nil || len(conversation.Messages) != 2 || !conversation.Messages[1].NewTestNeeded {
		t.Fatalf("legacy recommendation: %+v %v", conversation, err)
	}
	replyID := conversation.Messages[1].ID
	if _, err := p.ReplaceDraftWithNewTest(ctx, testID, source.ID, revision+1, replyID); !errors.Is(err, ErrConflict) {
		t.Fatalf("accepted a mismatching recommendation revision: %v", err)
	}
	if _, err := p.ReplaceDraftWithNewTest(ctx, testID, source.ID, revision, conversation.Messages[0].ID); !errors.Is(err, ErrConflict) {
		t.Fatalf("accepted a user message as the recommendation: %v", err)
	}
	before, err := p.Tests(ctx, source.WorkspaceID)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := p.DB.ExecContext(ctx, `CREATE FUNCTION reject_new_message() RETURNS trigger LANGUAGE plpgsql AS $$
 BEGIN RAISE EXCEPTION 'simulated write failure'; END; $$;
 CREATE TRIGGER reject_new_message BEFORE INSERT ON messages FOR EACH ROW EXECUTE FUNCTION reject_new_message()`); err != nil {
		t.Fatal(err)
	}
	if _, err := p.ReplaceDraftWithNewTest(ctx, testID, source.ID, revision, replyID); err == nil {
		t.Fatal("expected a failure writing the new conversation")
	}
	if _, err := p.DB.ExecContext(ctx, `DROP TRIGGER reject_new_message ON messages`); err != nil {
		t.Fatal(err)
	}
	unchanged, err := p.EditingSession(ctx, testID, source.ID)
	if err != nil || unchanged.Status != "active" || unchanged.Draft == nil || unchanged.Draft.Revision != revision {
		t.Fatalf("failed replacement modified the source: %+v %v", unchanged, err)
	}
	afterFailure, err := p.Tests(ctx, source.WorkspaceID)
	if err != nil || len(afterFailure) != len(before) {
		t.Fatalf("failed replacement left a new test: %d before, %d after, %v", len(before), len(afterFailure), err)
	}
	type outcome struct {
		TestReplacement
		err error
	}
	results := make(chan outcome, 2)
	for range 2 {
		go func() {
			replacement, err := p.ReplaceDraftWithNewTest(ctx, testID, source.ID, revision, replyID)
			results <- outcome{replacement, err}
		}()
	}
	first, retry := <-results, <-results
	if first.err != nil || retry.err != nil || first.Test.ID != retry.Test.ID || first.Test.ID == testID {
		t.Fatalf("replacement replay: %+v %+v", first, retry)
	}
	if first.SourceTest.ActiveEditingSession == nil || first.SourceTest.ActiveEditingSession.Status != "discarding" ||
		stringValue(first.SourceTest.PublishedVersionID) != stringValue(source.SourceVersionID) {
		t.Fatalf("unexpected source after replacement: %+v", first.SourceTest)
	}
	newTest := first.Test
	if newTest.Kind != "usecase" || newTest.WorkspaceID != source.WorkspaceID || newTest.PublishedVersionID != nil || newTest.ActiveEditingSession == nil {
		t.Fatalf("unexpected new test: %+v", newTest)
	}
	newConversation, err := p.Conversation(ctx, newTest.ID, newTest.ActiveEditingSession.ID)
	if err != nil || len(newConversation.Messages) != 1 || newConversation.Messages[0].Role != "user" || newConversation.Messages[0].Content != prompt {
		t.Fatalf("new conversation did not retain the exact prompt: %+v %v", newConversation, err)
	}
	after, err := p.Tests(ctx, source.WorkspaceID)
	if err != nil || len(after) != len(before)+1 {
		t.Fatalf("replacement created duplicate tests: %d before, %d after, %v", len(before), len(after), err)
	}
	h.release()
	if err := p.FinalizeDiscardingSessions(ctx); err != nil {
		t.Fatal(err)
	}
	if _, err := p.Draft(ctx, testID); !errors.Is(err, ErrNotFound) {
		t.Fatalf("source draft after Worker reclamation: %v", err)
	}
	replay, err := p.ReplaceDraftWithNewTest(ctx, testID, source.ID, revision, replyID)
	if err != nil || replay.Test.ID != newTest.ID || replay.SourceTest.Deleted != !published {
		t.Fatalf("replacement replay after Worker reclamation: %+v %v", replay, err)
	}
	queued := h.claim(stringValue(newConversation.ActiveRunID))
	if queued.Author.SkillID != "usecase-planner" || queued.Script != "" || queued.Author.SourceVersion != nil || len(queued.Author.Messages) != 1 || queued.Author.Messages[0].Content != prompt {
		t.Fatalf("new author run inherited source context: %+v", queued.Author)
	}
}
